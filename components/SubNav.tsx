// Pages where the sub-nav should be hidden (auth/utility pages)
const HIDDEN_ON = ['/login', '/register', '/pricing', '/stripe', '/invite', '/sso', '/privacy', '/terms'];

export default function SubNav() {
  const pathname = usePathname();

  if (HIDDEN_ON.some(p => pathname.startsWith(p))) return null;

  return (
    <div className="fixed top-16 left-0 right-0 z-30 border-b border-blue-900/20 bg-[#060b17]/95 backdrop-blur-md">
      <div className="flex items-center overflow-x-auto px-3 sm:px-6 scrollbar-none">
        {NAV_ITEMS.map(item => {
          const isActive = item.exact
            ? pathname === item.href
            : pathname === item.href || pathname.startsWith(item.href + '/') || pathname.startsWith(item.href + '?');

          return (
            <Link
              key={item.href + item.label}
              href={item.href}
              className={`
                flex flex-shrink-0 items-center gap-1.5 px-3 py-2.5 text-sm font-medium transition-colors border-b-2
                ${isActive
                  ? 'border-blue-500 text-blue-300'
                  : 'border-transparent text-slate-500 hover:text-slate-300 hover:border-slate-600'
                }
              `}
            >
              <span className={isActive ? 'text-blue-400' : 'text-slate-600'}>{item.icon}</span>
              {item.label}
            </Link>
          );
        })}
      </div>
    </div>
  );
}
